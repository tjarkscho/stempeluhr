function load() {
  try { return JSON.parse(localStorage.getItem(STORE)) || {}; } catch { return {}; }
}
const saved = load();
const mq = typeof matchMedia === 'function' ? matchMedia('(prefers-color-scheme: dark)') : null;
const browserFr = typeof navigator !== 'undefined' && /^fr/i.test(navigator.language || '');

export const prefs = {
  lang: saved.lang === 'fr' || saved.lang === 'de' ? saved.lang : (browserFr ? 'fr' : 'de'),
  theme: 'glas', // immer Glas, hell/dunkel automatisch wie das Gerät
  money: saved.money === 'chf' ? 'chf' : 'time',   // Saldo in Stunden oder Franken
  gauge: ['ring', 'glas', 'zeit', 'schlicht'].includes(saved.gauge) ? saved.gauge : 'ring',   // Darstellung der Arbeitszeit
};

// Gerät wechselt hell/dunkel -> sofort übernehmen
mq?.addEventListener?.('change', () => { if (prefs.theme === 'auto' || prefs.theme === 'glas') applyPrefs(); });

export function setPref(k, v) {
  prefs[k] = v;
  try { localStorage.setItem(STORE, JSON.stringify(prefs)); } catch { /* egal */ }
  applyPrefs();
}

export function applyPrefs() {
  const theme = prefs.theme === 'auto' ? (mq?.matches ? 'dunkel' : 'weiss')
    : prefs.theme === 'glas' ? (mq?.matches ? 'glas-dunkel' : 'glas-hell') : prefs.theme;   // Glas: hell/dunkel wie das Gerät
  const icon = ICON_OF[theme] || theme;
  document.documentElement.dataset.theme = theme;
  document.documentElement.lang = prefs.lang === 'fr' ? 'fr-CH' : 'de-CH';
  document.querySelector('meta[name="theme-color"]')?.setAttribute('content', THEME_COLOR[theme]);
  // Icons passend zum Farbschema
  const base = import.meta.env.BASE_URL;
  document.querySelector('link[rel="icon"]')?.setAttribute('href', `${base}favicon-${icon}.png?v=2`);
  document.querySelector('link[rel="apple-touch-icon"]')?.setAttribute('href', `${base}apple-touch-icon-${icon}.png?v=2`);
}

