/** Wörterbuch für PDFs; lang = 'de' | 'fr' */
export function pdfText(lang) {
  const t = lang === 'fr' ? FR : DE;
  return { ...t, label: (s) => (s ? t.labels[s] || s : s), today: () => new Date().toLocaleDateString(t.locale, { timeZone: 'Europe/Zurich' }) };
}
